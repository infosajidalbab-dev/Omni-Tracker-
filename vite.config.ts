function oauthCallbackPlugin() {
  return {
    name: 'oauth-callback-plugin',
    configureServer(server: any) {
      server.middlewares.use((req: any, res: any, next: any) => {
        const url = req.url || '';
        if (url.startsWith('/auth/callback') && !url.includes('.html')) {
          const query = url.includes('?') ? url.substring(url.indexOf('?')) : '';
          res.writeHead(302, { Location: `/auth/callback.html${query}` });
          res.end();
          return;
        }
        next();
      });
    },
  };
}

